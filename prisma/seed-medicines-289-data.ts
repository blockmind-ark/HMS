export interface ParsedMedicineItem {
  sNo: number;
  itemName: string;
  formPotencySpec: string;
  pkgPacks: number;
  nosPerPack: number;
  totalCost: number;
  perUnitCost: number;
  perPackCost: number;
  totalValue: number;
  perUnitSelling: number;
  qtyPurchased: number;
  batchNo: string;
  expiryDate: Date;
  isCredit: boolean;
}

export function parseMedicineLine(line: string): ParsedMedicineItem {
  const dotIndex = line.indexOf(".");
  const sNo = parseInt(line.substring(0, dotIndex).trim(), 10);
  const remainder = line.substring(dotIndex + 1).trim();

  let itemName = remainder;
  let formPotencySpec = "Standard Unit";

  if (remainder.includes(" - ")) {
    const parts = remainder.split(" - ");
    itemName = parts[0].trim();
    formPotencySpec = parts.slice(1).join(" - ").trim();
  }

  const lower = formPotencySpec.toLowerCase();
  let pkgPacks = 10;
  let nosPerPack = 30;
  let perPackCost = 450;
  let perUnitSelling = 20;

  if (
    lower.includes("susp") ||
    lower.includes("syrup") ||
    lower.includes("120ml") ||
    lower.includes("60ml") ||
    lower.includes("drops") ||
    lower.includes("lotion") ||
    lower.includes("liquid")
  ) {
    pkgPacks = 20;
    nosPerPack = 1;
    perPackCost = 120 + ((sNo * 7) % 180);
    perUnitSelling = Number((perPackCost * 1.28).toFixed(2));
  } else if (
    lower.includes("inj") ||
    lower.includes("ampoule") ||
    lower.includes("infusion") ||
    lower.includes("vaccine")
  ) {
    pkgPacks = 10;
    nosPerPack = 5;
    perPackCost = 350 + ((sNo * 19) % 800);
    const unitCost = perPackCost / nosPerPack;
    perUnitSelling = Number((unitCost * 1.35).toFixed(2));
  } else if (lower.includes("sachet") || lower.includes("powder")) {
    pkgPacks = 10;
    nosPerPack = 10;
    perPackCost = 600 + ((sNo * 13) % 400);
    const unitCost = perPackCost / nosPerPack;
    perUnitSelling = Number((unitCost * 1.3).toFixed(2));
  } else if (
    lower.includes("cream") ||
    lower.includes("gel") ||
    lower.includes("ointment") ||
    lower.includes("jelly")
  ) {
    pkgPacks = 15;
    nosPerPack = 1;
    perPackCost = 180 + ((sNo * 11) % 220);
    perUnitSelling = Number((perPackCost * 1.3).toFixed(2));
  } else if (lower.includes("inhaler")) {
    pkgPacks = 5;
    nosPerPack = 1;
    perPackCost = 850 + ((sNo * 17) % 500);
    perUnitSelling = Number((perPackCost * 1.25).toFixed(2));
  } else {
    pkgPacks = 10;
    nosPerPack = 30;
    perPackCost = 300 + ((sNo * 15) % 650);
    const unitCost = perPackCost / nosPerPack;
    perUnitSelling = Number((unitCost * 1.35).toFixed(2));
  }

  const qtyPurchased = pkgPacks * nosPerPack;
  const totalCost = Number((pkgPacks * perPackCost).toFixed(2));
  const perUnitCost = Number((perPackCost / nosPerPack).toFixed(2));
  const totalValue = Number((qtyPurchased * perUnitSelling).toFixed(2));

  const cleanCode = itemName.replace(/[^A-Za-z0-9]/g, "").substring(0, 4).toUpperCase();
  const batchNo = `${cleanCode}-26${String(sNo).padStart(3, "0")}`;

  const month = ((sNo * 3) % 12) + 1;
  const year = 2027 + (sNo % 3);
  const expiryDate = new Date(`${year}-${String(month).padStart(2, "0")}-28T00:00:00.000Z`);

  const isCredit = sNo % 3 === 0;

  return {
    sNo,
    itemName,
    formPotencySpec,
    pkgPacks,
    nosPerPack,
    totalCost,
    perUnitCost,
    perPackCost,
    totalValue,
    perUnitSelling,
    qtyPurchased,
    batchNo,
    expiryDate,
    isCredit,
  };
}

